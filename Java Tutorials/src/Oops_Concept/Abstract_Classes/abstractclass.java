public class abstractclass {

    /*
    Abstract Classes Rules:-

    1. if a class contains an abstract method then the class must be declared as abstract;
    2. all the abstract methods created in the parent class must be overridden in all the child classes;
    3. we cannot create an object of an abstract class. Because if we create an object of an abstract class,
       and if we call abstract method through the object, then it will give error since there is no body of the,
       abstract method;
    4. same for the constructor that we cannot create abstract constructors;
    5. we cannot create an abstract static methods because static methods cannot be overridden and abstract methods ,
       should be overridden, so there is no point of creating an abstract static method ,
       (we can create static method in abstract classes);
    6. we cannot use final keyword in abstract class, since final classes or methods cannot be inherited or overridden;
     */
}
